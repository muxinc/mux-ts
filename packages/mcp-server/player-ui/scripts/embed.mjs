import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, realpathSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const uiDir = fileURLToPath(new URL('..', import.meta.url));
const distFile = join(uiDir, 'dist', 'index.html');
const outFile = join(uiDir, '..', 'src', 'lib', 'player', 'player-html.ts');

const inputs = [
  'src',
  'index.html',
  'vite.config.ts',
  'package.json',
  'yarn.lock',
  'scripts/embed.mjs',
  '../src/lib/player/contract.ts',
];

function filesUnder(path) {
  const abs = join(uiDir, path);
  if (!statSync(abs).isDirectory()) return [path];
  return readdirSync(abs)
    .filter((name) => !name.startsWith('.'))
    .flatMap((name) => filesUnder(join(path, name)));
}

const inputFiles = inputs.flatMap(filesUnder).sort();

function sourceHash() {
  const hash = createHash('sha256');
  for (const file of inputFiles) {
    hash.update(`${file}\0`);
    hash.update(readFileSync(join(uiDir, file)));
  }
  return hash.digest('hex');
}

const EXTERNAL = String.raw`(?:https?:|//)`;
const EXTERNAL_ATTRIBUTE = new RegExp(
  String.raw`[\s/](?:src|href|xlink:href|action|poster|srcset)\s*=\s*(?:"\s*|'\s*|)${EXTERNAL}`,
  'gi',
);
const EXTERNAL_CSS = new RegExp(
  String.raw`url\(\s*["']?\s*${EXTERNAL}|@import\s+(?:url\(\s*)?["']?\s*${EXTERNAL}`,
  'gi',
);
const META_REFRESH = /<meta\b[^>]*\shttp-equiv\s*=\s*["']?\s*refresh/gi;
const SCRIPT_BODY = /(<script\b(?:"[^"]*"|'[^']*'|[^>"'])*>)[\s\S]*?<\/script/gi;

const withoutScriptBodies = (html) => html.replace(SCRIPT_BODY, '$1');

export function externalReferences(html) {
  const markup = withoutScriptBodies(html);
  return [EXTERNAL_ATTRIBUTE, EXTERNAL_CSS, META_REFRESH].flatMap((pattern) =>
    (markup.match(pattern) ?? []).map((match) => match.trim()),
  );
}

// Template literal contents survive `prettier --check` untouched. \r must be escaped because a raw CR in a template
// literal is normalised to LF.
const escapeForTemplate = (s) => s.replace(/[\\`\r]|\$\{/g, (m) => (m === '\r' ? '\\r' : `\\${m}`));

function check() {
  const committed = readFileSync(outFile, 'utf8');
  const committedHash = /PLAYER_SOURCE_HASH: string = '([0-9a-f]+)'/.exec(committed)?.[1];
  if (committedHash !== sourceHash()) {
    console.error('player-html.ts is stale. Run: yarn --cwd packages/mcp-server/player-ui build');
    process.exit(1);
  }
}

function write() {
  const builtAt = statSync(distFile).mtimeMs;
  const newer = inputFiles.filter((file) => statSync(join(uiDir, file)).mtimeMs > builtAt);
  if (newer.length > 0) {
    console.error(
      `dist/index.html is older than ${newer.join(
        ', ',
      )}. Run: yarn --cwd packages/mcp-server/player-ui build`,
    );
    process.exit(1);
  }

  const html = readFileSync(distFile, 'utf8');
  const external = externalReferences(html);
  if (external.length > 0) {
    console.error(
      `dist/index.html references files outside itself, which the host CSP would block:\n  ${external.join(
        '\n  ',
      )}`,
    );
    process.exit(1);
  }

  writeFileSync(
    outFile,
    [
      '// Generated by player-ui/scripts/embed.mjs from player-ui/dist/index.html. Do not edit.',
      '// Rebuild: yarn --cwd packages/mcp-server/player-ui build',
      '// The explicit `: string` keeps the multi-megabyte literal out of the emitted .d.ts (as local-docs-search.ts does).',
      `export const PLAYER_SOURCE_HASH: string = '${sourceHash()}';`,
      `export const PLAYER_HTML: string = \`${escapeForTemplate(html)}\`;`,
      '',
    ].join('\n'),
  );
  const kb = (bytes) => `${(bytes / 1024).toFixed(1)} KB`;
  console.log(
    `player-html.ts written: PLAYER_HTML ${kb(Buffer.byteLength(html))} (${kb(
      gzipSync(html).length,
    )} gzip), no external references`,
  );
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) check();
  else write();
}
